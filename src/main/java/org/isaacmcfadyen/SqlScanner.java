package org.isaacmcfadyen;

import java.util.ArrayList;
import java.util.List;

/** Finds the `?` placeholders of a SQL string, skipping quoted text and comments. */
final class SqlScanner {
    private SqlScanner() {}

    /** Character offsets of each `?` placeholder, in order. */
    static List<Integer> placeholders(String sql) {
        List<Integer> out = new ArrayList<>();
        int n = sql.length();
        for (int i = 0; i < n; i++) {
            char c = sql.charAt(i);
            if (c == '\'' || c == '"' || c == '`') {
                i = skipQuoted(sql, i, c);
            } else if (c == '[') {
                int end = sql.indexOf(']', i);
                i = end < 0 ? n : end;
            } else if (c == '-' && i + 1 < n && sql.charAt(i + 1) == '-') {
                int end = sql.indexOf('\n', i);
                i = end < 0 ? n : end;
            } else if (c == '/' && i + 1 < n && sql.charAt(i + 1) == '*') {
                int end = sql.indexOf("*/", i + 2);
                i = end < 0 ? n : end + 1;
            } else if (c == '?') {
                out.add(i);
                // "?NNN" numbered parameters are one placeholder; they are not generated by JDBC clients.
            }
        }
        return out;
    }

    private static int skipQuoted(String sql, int start, char quote) {
        for (int i = start + 1; i < sql.length(); i++) {
            if (sql.charAt(i) == quote) {
                if (i + 1 < sql.length() && sql.charAt(i + 1) == quote) i++;
                else return i;
            }
        }
        return sql.length();
    }

    private static final java.util.Set<String> WRITE_WORDS = java.util.Set.of("insert", "update", "delete", "replace");

    /** True for statements that produce rows even when the result is empty. */
    static boolean looksLikeQuery(String sql) {
        List<String> t = topLevelTokens(sql);
        if (t.isEmpty()) return false;
        String first = t.get(0).toLowerCase(java.util.Locale.ROOT);
        switch (first) {
            case "select": case "values": case "explain": return true;
            case "with": { // CTE bodies are parenthesised, so the first of these words at top level is the main statement
                for (String x : t) {
                    String w = x.toLowerCase(java.util.Locale.ROOT);
                    if (w.equals("select") || w.equals("values")) return true;
                    if (WRITE_WORDS.contains(w)) return false;
                }
                return false;
            }
            case "pragma": return isReadingPragma(t);
            default: return false;
        }
    }

    /** PRAGMAs that only read even with an argument; any other PRAGMA with an argument (`foreign_keys(0)`) sets something. */
    private static final java.util.Set<String> READ_WITH_ARGUMENT = java.util.Set.of("table_info", "table_xinfo", "table_list", "index_list", "index_info",
            "index_xinfo", "foreign_key_list", "foreign_key_check", "quick_check", "integrity_check");
    /** PRAGMAs that change something even without an argument. */
    private static final java.util.Set<String> WRITE_WITHOUT_ARGUMENT = java.util.Set.of("optimize", "shrink_memory", "incremental_vacuum", "wal_checkpoint");

    private static boolean isReadingPragma(List<String> t) {
        if (t.contains("=") || t.size() < 2) return false;
        int i = 1;
        if (t.size() > 3 && t.get(2).equals(".")) i = 3; // schema-qualified: main.table_info
        String name = t.get(i).toLowerCase(java.util.Locale.ROOT);
        boolean hasArgument = t.size() > i + 1 && t.get(i + 1).equals("(");
        return hasArgument ? READ_WITH_ARGUMENT.contains(name) : !WRITE_WITHOUT_ARGUMENT.contains(name);
    }

    /** First keyword of the statement, lower-cased, after comments and whitespace; "" for an empty statement. */
    static String firstKeyword(String sql) {
        List<String> t = topLevelTokens(sql);
        return t.isEmpty() ? "" : t.get(0).toLowerCase(java.util.Locale.ROOT);
    }

    /** True when a top-level (not parenthesised, not quoted) word equals the given keyword. */
    static boolean hasTopLevelWord(String sql, String word) {
        for (String t : topLevelTokens(sql)) if (t.equalsIgnoreCase(word)) return true;
        return false;
    }

    /** `SELECT * FROM ...` or `SELECT DISTINCT * ...`: the result columns are exactly the table's columns. */
    static boolean selectsAllColumns(String sql) {
        List<String> t = topLevelTokens(sql);
        int i = 1;
        while (i < t.size() && (t.get(i).equalsIgnoreCase("distinct") || t.get(i).equalsIgnoreCase("all"))) i++;
        return t.size() > i && t.get(0).equalsIgnoreCase("select") && t.get(i).equals("*");
    }

    /** `sql` with `LIMIT n` appended, so that setMaxRows does not transfer a whole table; null when it cannot be done safely. */
    static String withLimit(String sql, int n) {
        if (n <= 0 || !firstKeyword(sql).equals("select") || !isSingleRead(sql) || hasTopLevelWord(sql, "limit")) return null;
        String s = sql.stripTrailing();
        if (s.endsWith(";")) s = s.substring(0, s.length() - 1).stripTrailing();
        return s + "\nLIMIT " + n; // newline: a trailing -- comment must not swallow the LIMIT
    }

    private static final java.util.Set<String> CLAUSE_END = java.util.Set.of("where", "group", "order", "limit", "having", "window", "offset");
    private static final java.util.Set<String> MULTI_SOURCE = java.util.Set.of("join", "natural", "cross", "inner", "left", "right", "full", "outer", "union", "intersect", "except");

    /** Depth-0 tokens: quoted text and words stay whole; anything else is one token per character; parenthesised text is dropped. */
    private static List<String> topLevelTokens(String sql) {
        List<String> out = new ArrayList<>();
        int depth = 0;
        int n = sql.length();
        for (int i = 0; i < n; i++) {
            char c = sql.charAt(i);
            if (c == '-' && i + 1 < n && sql.charAt(i + 1) == '-') {
                int end = sql.indexOf('\n', i);
                i = end < 0 ? n : end;
            } else if (c == '/' && i + 1 < n && sql.charAt(i + 1) == '*') {
                int end = sql.indexOf("*/", i + 2);
                i = end < 0 ? n : end + 1;
            } else if (c == '(') {
                if (depth++ == 0) out.add("(");
            } else if (c == ')') {
                depth = Math.max(0, depth - 1);
            } else if (c == '\'' || c == '"' || c == '`' || c == '[') {
                int end = c == '[' ? sql.indexOf(']', i) : skipQuoted(sql, i, c);
                end = end < 0 ? n - 1 : end;
                if (depth == 0) out.add(sql.substring(i, end + 1));
                i = end;
            } else if (depth == 0 && (Character.isLetterOrDigit(c) || c == '_' || c == '$')) {
                int j = i;
                while (j < n && (Character.isLetterOrDigit(sql.charAt(j)) || sql.charAt(j) == '_' || sql.charAt(j) == '$')) j++;
                out.add(sql.substring(i, j));
                i = j - 1;
            } else if (depth == 0 && !Character.isWhitespace(c)) {
                out.add(String.valueOf(c));
            }
        }
        return out;
    }

    private static String unquote(String identifier) {
        char c = identifier.charAt(0);
        if (c == '"' || c == '`') return identifier.substring(1, identifier.length() - 1).replace(String.valueOf(c) + c, String.valueOf(c));
        if (c == '[') return identifier.substring(1, identifier.length() - 1);
        return identifier;
    }

    /** The one table a plain `SELECT ... FROM t [alias] [WHERE ...]` reads from, or null for joins, unions, subqueries and non-selects. */
    static String singleTable(String sql) {
        List<String> t = topLevelTokens(sql);
        if (t.isEmpty() || !t.get(0).equalsIgnoreCase("select")) return null;
        int from = -1;
        for (int i = 1; i < t.size(); i++) {
            String k = t.get(i).toLowerCase(java.util.Locale.ROOT);
            if (k.equals("from")) {
                from = i;
                break;
            }
            if (MULTI_SOURCE.contains(k) || k.equals(";")) return null;
        }
        if (from < 0 || from + 1 >= t.size() || t.get(from + 1).equals("(")) return null;
        int i = from + 1;
        String name = unquote(t.get(i));
        while (i + 2 < t.size() && t.get(i + 1).equals(".")) { // schema-qualified: main.t
            name = unquote(t.get(i + 2));
            i += 2;
        }
        i++;
        if (i < t.size() && t.get(i).equalsIgnoreCase("as")) i += 2;
        else if (i < t.size() && !CLAUSE_END.contains(t.get(i).toLowerCase(java.util.Locale.ROOT)) && !t.get(i).equals(";") && !MULTI_SOURCE.contains(t.get(i).toLowerCase(java.util.Locale.ROOT)) && !t.get(i).equals(",")) i++;
        for (; i < t.size(); i++) {
            String k = t.get(i).toLowerCase(java.util.Locale.ROOT);
            if (CLAUSE_END.contains(k)) break;
            if (!k.equals(";")) return null; // comma, join or anything else before the WHERE: more than one source
        }
        for (; i < t.size(); i++) {
            if (t.get(i).equalsIgnoreCase("union") || t.get(i).equalsIgnoreCase("intersect") || t.get(i).equalsIgnoreCase("except")) return null;
        }
        return name;
    }

    /** One SELECT/VALUES/EXPLAIN or read-only PRAGMA statement: safe to send twice. WITH is excluded (it can wrap a DELETE). */
    static boolean isSingleRead(String sql) {
        List<String> t = topLevelTokens(sql);
        if (t.isEmpty()) return false;
        for (int i = 0; i < t.size() - 1; i++) if (t.get(i).equals(";")) return false;
        String first = t.get(0).toLowerCase(java.util.Locale.ROOT);
        return first.equals("select") || first.equals("values") || first.equals("explain") || (first.equals("pragma") && isReadingPragma(t));
    }

    /** Lower-cased aliases declared in the select list of a SELECT (`expr AS x` or `expr x`). */
    static java.util.Set<String> selectAliases(String sql) {
        java.util.Set<String> out = new java.util.HashSet<>();
        List<String> t = topLevelTokens(sql);
        if (t.isEmpty() || !t.get(0).equalsIgnoreCase("select")) return out;
        List<String> item = new ArrayList<>();
        for (int i = 1; i <= t.size(); i++) {
            String tok = i < t.size() ? t.get(i) : "from";
            if (tok.equals(",") || tok.equalsIgnoreCase("from")) {
                int n = item.size();
                if (n >= 2) {
                    String last = item.get(n - 1);
                    String prev = item.get(n - 2);
                    boolean identifier = Character.isLetter(last.charAt(0)) || last.charAt(0) == '_' || last.charAt(0) == '"' || last.charAt(0) == '`' || last.charAt(0) == '[';
                    if (identifier && !prev.equals(".")) out.add(unquote(last).toLowerCase(java.util.Locale.ROOT));
                }
                item.clear();
                if (tok.equalsIgnoreCase("from")) break;
            } else if (!tok.equalsIgnoreCase("distinct") && !tok.equalsIgnoreCase("all") || !item.isEmpty()) {
                item.add(tok);
            }
        }
        return out;
    }

    /**
     * The statements of a SQL string, split at top-level `;` (outside quotes, comments and parentheses); empty ones dropped.
     * A CREATE TRIGGER body also contains `;`, so callers must check that the count matches what D1 answered.
     */
    static List<String> splitStatements(String sql) {
        List<String> out = new ArrayList<>();
        int depth = 0;
        int start = 0;
        int n = sql.length();
        for (int i = 0; i <= n; i++) {
            char c = i < n ? sql.charAt(i) : ';';
            if (i < n && (c == '\'' || c == '"' || c == '`')) {
                i = skipQuoted(sql, i, c);
            } else if (i < n && c == '[') {
                int end = sql.indexOf(']', i);
                i = end < 0 ? n - 1 : end;
            } else if (i < n && c == '-' && i + 1 < n && sql.charAt(i + 1) == '-') {
                int end = sql.indexOf('\n', i);
                i = end < 0 ? n - 1 : end;
            } else if (i < n && c == '/' && i + 1 < n && sql.charAt(i + 1) == '*') {
                int end = sql.indexOf("*/", i + 2);
                i = end < 0 ? n - 1 : end + 1;
            } else if (c == '(') {
                depth++;
            } else if (c == ')') {
                depth = Math.max(0, depth - 1);
            } else if (c == ';' && (depth == 0 || i == n)) {
                String part = sql.substring(start, Math.min(i, n));
                if (!topLevelTokens(part).isEmpty()) out.add(part.strip());
                start = i + 1;
            }
        }
        return out;
    }

    /** True when every statement only reads (what a read-only connection may run). */
    static boolean onlyReads(String sql) {
        List<String> statements = splitStatements(sql);
        if (statements.isEmpty()) return false;
        for (String s : statements) if (!looksLikeQuery(s)) return false;
        return true;
    }
}
